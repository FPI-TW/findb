"""Generate consumer-specific metadata without publishing Fetcher schedule settings."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_ROOT.parent
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))

from app.provider_catalog import ProviderCatalog, load_catalog  # noqa: E402

CATALOG_PATH = Path("backend/configs/provider_catalog.v1.json")


def json_text(value: object) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def projection_digest(value: object) -> str:
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()


def build_artifacts(catalog: ProviderCatalog) -> dict[Path, str]:
    data = catalog.canonical_data()
    envelope = {"schema_version": 1, "source_sha256": catalog.digest()}
    source_scopes = {
        provider["provider"]: sorted(
            feed["dataset_key"]
            for feed in data["feeds"]
            if feed["provider"] == provider["provider"] and feed["capabilities"]["source"]
        )
        for provider in data["providers"]
        if any(
            feed["provider"] == provider["provider"] and feed["capabilities"]["source"]
            for feed in data["feeds"]
        )
    }
    # Positive projection: adding a Backend field can never accidentally publish it
    # to the independent Fetcher package. Neither clock nor schedule enters this view.
    fetcher = {
        "schema_version": 1,
        "providers": [
            {
                "provider": p["provider"],
                "credential_env_names": p["credential_env_names"],
                "platform_limits": p["platform_limits"],
            }
            for p in data["providers"]
        ],
        "feeds": [
            {
                key: feed[key]
                for key in (
                    "provider",
                    "dataset_key",
                    "market",
                    "calendar_market",
                    "asset_class",
                    "frequency",
                    "contract",
                    "lifecycle",
                    "capabilities",
                    "delivery",
                    "historical_execution",
                )
            }
            for feed in data["feeds"]
        ],
    }
    fetcher["projection_sha256"] = projection_digest(fetcher)
    consumers = sorted(
        (
            {
                "name": f"findb-{role.replace('_', '-')}-{p['container_suffix']}",
                "provider": p["provider"],
                "role": role,
                "image_key": p["image_key"],
            }
            for p in data["providers"]
            for role in p["consumer_roles"]
        ),
        key=lambda row: row["name"],
    )
    inventory = {
        "schema_version": 1,
        "images": sorted({p["image_key"] for p in data["providers"]}),
        "providers": [p["provider"] for p in data["providers"]],
        "consumers": consumers,
    }
    inventory["projection_sha256"] = projection_digest(inventory)
    dataset_markets = {feed["dataset_key"]: feed["market"] for feed in data["feeds"]}
    dashboard_metadata = {"source_scopes": source_scopes, "dataset_markets": dataset_markets}
    # Render small TypeScript literals in the repository's Prettier style, without
    # requiring Node in the Python-only contract-export job.
    lines = [
        "// Generated by backend/scripts/export_provider_catalog.py; do not edit.",
        "export const PROVIDER_METADATA_SHA256 =",
        f'  "{projection_digest(dashboard_metadata)}"',
        "export const PROVIDER_CATALOG_VERSION = 1 as const",
        "export const SOURCE_PROVIDERS = [",
        *(f'  "{provider}",' for provider in source_scopes),
        "] as const",
        "export type SourceProvider = (typeof SOURCE_PROVIDERS)[number]",
        "export const SOURCE_PROVIDER_DATASETS = {",
        *(f"  {provider}: {json.dumps(datasets)}," for provider, datasets in source_scopes.items()),
        "} as const satisfies Record<SourceProvider, readonly string[]>",
        "export const DATASET_MARKETS: Record<string, string> = {",
        *(
            f'  {feed.dataset_key}: "{feed.market}",'
            for feed in sorted(catalog.feeds, key=lambda f: f.dataset_key)
        ),
        "}",
        "",
    ]
    provider_type = (
        '"""Generated provider identities; historical evidence keeps explicit retired types."""\n\n'
        "from typing import Literal\n\n"
        "ProviderId = Literal[" + ", ".join(json.dumps(p) for p in source_scopes) + "]\n"
    )
    artifacts = {
        Path("backend/app/generated/provider_ids.py"): provider_type,
        Path("backend/configs/provider_catalog.v1.schema.json"): json_text(
            ProviderCatalog.model_json_schema()
        ),
        Path("backend/app/generated/provider_metadata.v1.json"): json_text(
            {**data, **envelope, "source_scopes": source_scopes}
        ),
        Path("fetcher/src/findb_fetcher/data/execution_descriptors.v1.json"): json_text(fetcher),
        Path("dashboard/src/lib/generated/provider-catalog.ts"): "\n".join(lines),
        Path("infra/deploy/generated/provider_inventory.v1.json"): json_text(inventory),
    }

    # Standalone SSM guards and the host metric publisher must carry the same
    # generated inventory when copied without the source tree. Regenerate the
    # marked inventory in each embedded script.
    block = "# BEGIN GENERATED PROVIDER INVENTORY\n"
    block += "PROVIDERS = " + repr(tuple(inventory["providers"])).replace("'", '"') + "\n"
    block += "CONSUMERS = (\n"
    for row in consumers:
        block += (
            "    ("
            + ", ".join(json.dumps(row[k]) for k in ("name", "provider", "role", "image_key"))
            + "),\n"
        )
    block += ")\nEXPECTED_RUNTIMES = tuple(row[0] for row in CONSUMERS)\n"
    block += "# END GENERATED PROVIDER INVENTORY"
    for path in (
        Path("infra/deploy/check_fetcher_host.py"),
        Path("infra/deploy/check_fetcher_runtime_recovery.py"),
        Path("infra/deploy/inspect_full_market_installation.py"),
        Path("infra/deploy/provider_work_preflight.py"),
        Path("infra/monitoring/publish_staging_metrics.py"),
    ):
        text = (REPO_ROOT / path).read_text()
        start = text.index("# BEGIN GENERATED PROVIDER INVENTORY")
        end = text.index("# END GENERATED PROVIDER INVENTORY") + len(
            "# END GENERATED PROVIDER INVENTORY"
        )
        artifacts[path] = text[:start] + block + text[end:]
    return artifacts


def export(root: Path, *, check: bool) -> list[Path]:
    catalog = load_catalog(root / CATALOG_PATH, contracts_dir=root / "contracts")
    artifacts = build_artifacts(catalog)
    stale = []
    for relative, expected in artifacts.items():
        path = root / relative
        if check:
            if not path.is_file() or path.read_text() != expected:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = export(REPO_ROOT, check=args.check)
    if stale:
        raise SystemExit("Stale provider metadata artifacts: " + ", ".join(map(str, stale)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
